#!/usr/bin/env python3
"""Affine-fibre route (paper 4, Theorem M) from the GRAPH ALONE, prototype (2026-10-24).

Recovers the Muzychuk-CFI structure G(sigma) of a graph without knowing sigma, then runs the algorithm of Theorem M:
  1. fibres  : pairs with the maximal number of common neighbours are same-fibre pairs differing in two coordinates
               (Lemma M1, needs m >= 5 or m = 4, q >= 3); the fibres are the components of that pair graph;
  2. coords  : for fibres F_i, F_j the traces N(w) ∩ F_i (w in F_j) are the q classes of coordinate j of F_i;
  3. labels  : any labelling of the classes by Z_q under which F_i is the set of sum-zero vectors; built from an origin
               x0 and the Latin square of three coordinates (addition read off the graph); by Lemma M2 it differs from
               the true one by an affine map with a common unit, which the (rho, u) enumeration absorbs;
  4. sigma^  : sigma^_ij(a) = label of the class of coordinate i in F_j met by the neighbours of class a; then every edge
               is checked against sigma^ and the edge count must be C(m,2) q^(2m-5), so G is exactly G(sigma^);
  5. solve   : for every rho in S_m (backtracking with pruning) and units u, the conditions are pairs (c_ij, c_ji) per
               edge plus sum_j c_ij = 0 per fibre; count by a DP over the edges, extract one solution per (rho, u);
               the translations (rho = id, u = 1) form an abelian group T <= Z_q^N, generated by solutions until its
               order (HNF) equals the DP count.
Output: |Aut(G)| (exact by Lemmas M1, M2), generators each verified on the graph, or "not applicable" with the reason.
Usage: muz_route.py graph.dimacs [--shuffle SEED]"""
import sys, itertools, math, random, time
from collections import defaultdict
import numpy as np


def load(path):
    n = 0; E = []
    for line in open(path):
        p = line.split()
        if not p: continue
        if p[0] == 'p': n = int(p[2])
        elif p[0] == 'e': E.append((int(p[1]) - 1, int(p[2]) - 1))
    return n, E


class NA(Exception):
    pass


def structure(n, adj):
    A = np.zeros((n, n), dtype=np.int32)
    for v in range(n):
        A[v, list(adj[v])] = 1
    C = A @ A
    np.fill_diagonal(C, -1)
    cmax = C.max()
    # fibres: components of the max-common-neighbour graph, and no edges inside a fibre
    seen = [-1] * n; fibres = []
    for s in range(n):
        if seen[s] >= 0: continue
        comp = [s]; seen[s] = len(fibres); k = 0
        while k < len(comp):
            u = comp[k]; k += 1
            for w in np.nonzero(C[u] == cmax)[0]:
                if seen[w] < 0: seen[w] = len(fibres); comp.append(int(w))
        fibres.append(comp)
    m = len(fibres)
    if m < 4: raise NA(f"{m} fibres")
    sz = len(fibres[0])
    if any(len(f) != sz for f in fibres): raise NA("unequal fibres")
    for f in fibres:
        fs = set(f)
        if any(w in fs for v in f for w in adj[v]): raise NA("edge inside a fibre")
    q = round(sz ** (1.0 / (m - 2)))
    if q ** (m - 2) != sz or q < 2: raise NA(f"fibre size {sz} is not q^(m-2) for m={m}")
    if m == 4 and q < 3: raise NA("m=4 needs q>=3")
    return fibres, m, q, seen


def coords(fibres, adj, m, q):
    """cls[i][j]: dict vertex of F_i -> class id (0..q-1, arbitrary) of coordinate j; rep[i][j][c] = frozenset."""
    cls = [[None] * m for _ in range(m)]; members = [[None] * m for _ in range(m)]
    for i in range(m):
        Fi = set(fibres[i])
        for j in range(m):
            if j == i: continue
            traces = {}
            for w in fibres[j]:
                t = frozenset(x for x in adj[w] if x in Fi)
                traces.setdefault(t, []).append(w)
            ts = list(traces)
            if len(ts) != q or sum(len(t) for t in ts) != len(Fi): raise NA(f"traces of F{j} on F{i} are not a partition into q")
            d = {}
            for c, t in enumerate(ts):
                for x in t: d[x] = c
            cls[i][j] = d; members[i][j] = ts
    return cls, members


def labels(fibres, cls, m, q):
    """lab[i][j][c] in Z_q such that every vertex of F_i has label-sum 0."""
    lab = [[None] * m for _ in range(m)]
    for i in range(m):
        others = [j for j in range(m) if j != i]
        F = fibres[i]; x0 = F[0]
        key = lambda x: tuple(cls[i][j][x] for j in others)
        index = {key(x): x for x in F}
        if len(index) != len(F): raise NA("coordinates do not determine the vertex")
        k0 = key(x0)
        j1, j2, j3 = others[0], others[1], others[2]
        p1, p2, p3 = 0, 1, 2

        def vertex_with(changes):   # classes of x0 with some coordinates changed (positions in `others`)
            kk = list(k0)
            for pos, c in changes.items(): kk[pos] = c
            return index.get(tuple(kk))
        # f: class a of j1 -> class b of j2 with (a, b, 0) present (b = -a);  g similarly into j3
        f = {}; g = {}
        for a in range(q):
            for b in range(q):
                if vertex_with({p1: a, p2: b}) is not None: f[a] = b
                if vertex_with({p1: a, p3: b}) is not None: g[a] = b
        if len(f) != q or len(g) != q: raise NA("Latin structure missing")
        h = {}   # (b in j2, c in j3) -> a in j1 with (a,b,c) present: a = -b-c
        for b in range(q):
            for c in range(q):
                for a in range(q):
                    if vertex_with({p1: a, p2: b, p3: c}) is not None: h[(b, c)] = a
        add = lambda a1, a2: h[(f[a1], g[a2])]   # a1 + a2 on classes of j1
        zero = k0[p1]
        gen = None
        for cand in range(q):
            s, k = cand, 1
            while s != zero: s = add(s, cand); k += 1
            if k == q: gen = cand; break
        if gen is None: raise NA("no generator: coordinate group is not cyclic of order q")
        L1 = {zero: 0}; s = zero
        for t in range(1, q):
            s = add(s, gen) if t > 1 else gen
            L1[s] = t
        if len(L1) != q: raise NA("labelling failed")
        lab[i][j1] = L1
        lab[i][j2] = {f[a]: (-t) % q for a, t in L1.items()}
        # every other coordinate j: vertex (a, b, c_j) with the rest at x0: c_j = -(a + b) ... use b = x0's class (label 0)
        for pos, j in enumerate(others):
            if j in (j1, j2): continue
            Lj = {}
            for a, t in L1.items():
                for c in range(q):
                    if vertex_with({p1: a, pos: c}) is not None: Lj[c] = (-t) % q
            if len(Lj) != q: raise NA("labelling of a coordinate failed")
            lab[i][j] = Lj
        for x in F:
            if sum(lab[i][j][cls[i][j][x]] for j in others) % q: raise NA("labelled fibre is not the sum-zero set")
    return lab


def sigma_hat(fibres, adj, cls, lab, members, m, q):
    sig = {}
    for i in range(m):
        for j in range(m):
            if i == j: continue
            s = [None] * q
            for c, t in enumerate(members[i][j]):
                a = lab[i][j][c]
                x = next(iter(t))
                nb = [w for w in adj[x] if w in cls[j][i]]
                bset = {lab[j][i][cls[j][i][w]] for w in nb}
                if len(bset) != 1: raise NA("neighbours of a class are not one class")
                s[a] = bset.pop()
            if sorted(s) != list(range(q)): raise NA("sigma is not a bijection")
            sig[(i, j)] = s
    for (i, j), s in sig.items():
        if any(sig[(j, i)][s[t]] != t for t in range(q)): raise NA("sigma_ji != sigma_ij^-1")
    return sig


def solve(m, q, sig):
    units = [u for u in range(1, q) if math.gcd(u, q) == 1]
    edges = list(itertools.combinations(range(m), 2))
    # allowed[(i,j,ti,tj,ui)] -> {uj: [(cij, cji)]}  for target pair (ti,tj) = (rho i, rho j)
    allowed = {}
    for (i, j) in edges:
        sinv = sig[(j, i)]
        for ti in range(m):
            for tj in range(m):
                if ti == tj: continue
                s2 = sig[(ti, tj)]
                for ui in units:
                    d = defaultdict(list)
                    for cij in range(q):
                        pij = [(ui * t + cij) % q for t in range(q)]
                        pji = [s2[pij[sinv[y]]] for y in range(q)]
                        c = pji[0]; u = (pji[1] - c) % q
                        if u in units and all(pji[t] == (u * t + c) % q for t in range(q)):
                            d[u].append((cij, c))
                    allowed[(i, j, ti, tj, ui)] = dict(d)
    results = []   # (rho, u, count, one solution dict)

    def count_and_one(rho, u):
        # DP over edges, state = tuple of partial sums per fibre; also keep one witness per state
        state = {tuple([0] * m): ()}
        cnt = {tuple([0] * m): 1}
        for (i, j) in edges:
            opts = allowed[(i, j, rho[i], rho[j], u[i])].get(u[j], [])
            if not opts: return 0, None
            nc = defaultdict(int); nw = {}
            for st, c0 in cnt.items():
                for (a, b) in opts:
                    s2 = list(st); s2[i] = (s2[i] + a) % q; s2[j] = (s2[j] + b) % q; s2 = tuple(s2)
                    nc[s2] += c0
                    if s2 not in nw: nw[s2] = state[st] + ((i, j, a, b),)
            cnt, state = nc, nw
        z = tuple([0] * m)
        return cnt.get(z, 0), state.get(z)

    rho = [None] * m; used = [False] * m; u = [None] * m

    def extend(i):
        if i == m:
            c, w = count_and_one(rho, u)
            if c: results.append((tuple(rho), tuple(u), c, w))
            return
        for t in range(m):
            if used[t]: continue
            for ui in units:
                rho[i] = t; u[i] = ui
                ok = True
                for k in range(i):   # pairwise feasibility with earlier fibres
                    if not allowed[(k, i, rho[k], t, u[k])].get(ui): ok = False; break
                if ok:
                    used[t] = True; extend(i + 1); used[t] = False
        rho[i] = None; u[i] = None
    extend(0)
    return results, allowed, edges, units


def to_perm(rho, u, sol, fibres, cls, lab, m, q, n):
    """vertex map of the automorphism (rho, u, c): (x,i) -> ((u_i x_j + c_ij)_{rho j}, rho i)."""
    c = {}
    for (i, j, a, b) in sol: c[(i, j)] = a; c[(j, i)] = b
    # index of target fibre by label vector
    idx = {}
    for i in range(m):
        others = [j for j in range(m) if j != i]
        for x in fibres[i]:
            idx[(i, tuple(lab[i][j][cls[i][j][x]] for j in others))] = x
    perm = [None] * n
    for i in range(m):
        others = [j for j in range(m) if j != i]
        ti = rho[i]; tothers = [j for j in range(m) if j != ti]
        for x in fibres[i]:
            y = [None] * m
            for j in others: y[rho[j]] = (u[i] * lab[i][j][cls[i][j][x]] + c[(i, j)]) % q
            perm[x] = idx[(ti, tuple(y[j] for j in tothers))]
    return perm


def hnf_order(vecs, N, q):
    """order of the subgroup of Z_q^N generated by vecs: q^N / det(HNF of span(vecs) + q Z^N)."""
    import sympy
    rows = [list(v) for v in vecs] + [[q if k == t else 0 for k in range(N)] for t in range(N)]
    M = sympy.Matrix(rows)
    from sympy.matrices.normalforms import hermite_normal_form
    H = hermite_normal_form(M.T).T if False else None
    # determinant of the lattice = product of the diagonal of an echelon basis; use Smith form on the integer matrix
    from sympy.matrices.normalforms import smith_normal_form
    S = smith_normal_form(M, domain=sympy.ZZ)
    d = 1
    for k in range(N): d *= abs(S[k, k])
    return q ** N // d


def main():
    path = sys.argv[1]; t0 = time.time()
    n, E = load(path)
    if '--shuffle' in sys.argv:
        r = random.Random(int(sys.argv[sys.argv.index('--shuffle') + 1])); p = list(range(n)); r.shuffle(p)
        E = [(p[a], p[b]) for a, b in E]
    adj = [set() for _ in range(n)]
    for a, b in E: adj[a].add(b); adj[b].add(a)
    try:
        fibres, m, q, fib_of = structure(n, adj)
        cls, members = coords(fibres, adj, m, q)
        lab = labels(fibres, cls, m, q)
        sig = sigma_hat(fibres, adj, cls, lab, members, m, q)
        # every edge obeys sigma^ and the edge count is exact: then G is exactly G(sigma^) and Theorem M applies
        for a, b in E:
            i, j = fib_of[a], fib_of[b]
            if sig[(i, j)][lab[i][j][cls[i][j][a]]] != lab[j][i][cls[j][i][b]]: raise NA("an edge breaks the sigma rule")
        if len(E) != m * (m - 1) // 2 * q ** (2 * m - 5): raise NA(f"edge count {len(E)} != {m*(m-1)//2*q**(2*m-5)}")
    except NA as e:
        print(f"MUZROUTE {path} NOT APPLICABLE: {e} ({time.time()-t0:.1f}s)"); return
    t1 = time.time()
    results, allowed, edges, units = solve(m, q, sig)
    order = sum(r[2] for r in results)
    # generators: one solution per (rho, u), plus the translation group T
    gens = [to_perm(r[0], r[1], r[3], fibres, cls, lab, m, q, n) for r in results]
    ident = tuple(range(m)); one = tuple([1] * m)
    tcount = next((r[2] for r in results if r[0] == ident and r[1] == one), 0)
    N = m * (m - 1); tvecs = []
    if tcount > 1:
        # random solutions at (id, 1) until the generated subgroup has order tcount
        opts = [allowed[(i, j, i, j, 1)].get(1, []) for (i, j) in edges]
        rng = random.Random(1); tries = 0
        pos = {(i, j): k for k, (i, j) in enumerate([(i, j) for i in range(m) for j in range(m) if i != j])}
        while (not tvecs or hnf_order(tvecs, N, q) < tcount) and tries < 200:
            tries += 1
            # random backtracking for a solution with fibre sums 0
            def rb(k, sums, acc):
                if k == len(edges):
                    return acc if all(s == 0 for s in sums) else None
                i, j = edges[k]; o = opts[k][:]; rng.shuffle(o)
                for (a, b) in o:
                    s2 = list(sums); s2[i] = (s2[i] + a) % q; s2[j] = (s2[j] + b) % q
                    r = rb(k + 1, s2, acc + [(i, j, a, b)])
                    if r is not None: return r
                return None
            sol = rb(0, [0] * m, [])
            if sol is None: break
            v = [0] * N
            for (i, j, a, b) in sol: v[pos[(i, j)]] = a; v[pos[(j, i)]] = b
            tvecs.append(v); gens.append(to_perm(ident, one, sol, fibres, cls, lab, m, q, n))
    # verify every generator on the graph
    bad = sum(1 for g in gens if any(g[b] not in adj[g[a]] for a, b in E))
    tord = hnf_order(tvecs, N, q) if tvecs else 1
    status = "EXACT" if bad == 0 and (tcount <= 1 or tord == tcount) else "FAILED"
    print(f"MUZROUTE {path} m={m} q={q} n={n}: |Aut| = {order} ({len(results)} (rho,u) classes, |T| = {tcount}, "
          f"T generated {tord}) generators {len(gens)} verified={bad == 0} {status} "
          f"structure {t1-t0:.1f}s solve {time.time()-t1:.1f}s")


if __name__ == '__main__':
    main()
